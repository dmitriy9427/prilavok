/**
 * Пауза перед повторным подключением.
 *
 * ─── Почему не «сразу» и не «каждую секунду» ────────────────────────────────
 * Сервер упал. Если 10 000 клиентов переподключаются немедленно и повторяют
 * каждую секунду, поднявшийся сервер получает 10 000 подключений в секунду и
 * падает снова. Это называют thundering herd — «стадо бизонов».
 *
 * Два приёма против этого:
 *
 * 1. Экспоненциальный рост (exponential backoff): каждая следующая пауза
 *    вдвое длиннее — 0,5 с, 1 с, 2 с, 4 с… до потолка в 30 с. Короткий сбой
 *    лечится быстро, а при долгом клиенты не долбят сервер.
 *
 * 2. Случайный разброс (jitter). Без него все клиенты, отключённые в один
 *    момент, приходят обратно ОДНОВРЕМЕННО — просто реже. Случайная добавка
 *    размазывает их по времени. Здесь «equal jitter»: половина паузы
 *    фиксирована, вторая половина случайна — пауза не бывает почти нулевой.
 */
export type BackoffOptions = {
  /** Первая пауза, мс. */
  base: number
  /** Потолок, мс. */
  max: number
  /** Во сколько раз растёт пауза. */
  factor: number
}

export const DEFAULT_BACKOFF: BackoffOptions = { base: 500, max: 30_000, factor: 2 }

/**
 * @param attempt номер попытки с нуля: 0 — первая повторная
 * @param random  источник случайности [0, 1) — подменяется в тестах
 */
export function backoffDelay(attempt: number, options: BackoffOptions = DEFAULT_BACKOFF, random: () => number = Math.random) {
  const ceiling = Math.min(options.max, options.base * options.factor ** attempt)
  return Math.round(ceiling / 2 + random() * (ceiling / 2))
}
